CREATE OR REPLACE FUNCTION public.kho_variant_mirror_guard()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  target_mirrors uuid;
  target_has_children boolean;
  self_has_children boolean;
begin
  if new.mirrors_variant_id is null then
    return new;
  end if;
  if new.mirrors_variant_id = new.id then
    raise exception 'Không thể liên kết một biến thể với chính nó';
  end if;
  select mirrors_variant_id into target_mirrors from public.kho_variants where id = new.mirrors_variant_id;
  if target_mirrors is not null then
    raise exception 'Biến thể đích đang liên kết với biến thể khác — hãy chọn biến thể gốc thật sự (không liên kết chuỗi)';
  end if;
  select exists(select 1 from public.kho_variants where mirrors_variant_id = new.id) into self_has_children;
  if self_has_children then
    raise exception 'Biến thể này đang là gốc cho biến thể khác — hãy gỡ liên kết đó trước';
  end if;
  return new;
end;
$function$;

