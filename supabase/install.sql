begin
  if not exists (select 1 from kho_variants where id = p_variant_id) then
    raise exception 'Khong tim thay bien the %', p_variant_id;
  end if;

  perform kho_ensure_item_for_variant(p_variant_id);

  for r in
    select b.item_id, b.qty from kho_variant_bom b
    where b.variant_id = p_variant_id order by b.item_id
  loop
    update kho_items set stock = stock + (p_change * r.qty) where id = r.item_id;

    insert into kho_stock_movements
      (variant_id, item_id, change, reason, direction, note, via_variant_id)
    select coalesce(i.source_variant_id, p_variant_id), i.id, p_change * r.qty,
           p_reason, p_direction, p_note,
           case when coalesce(i.source_variant_id, p_variant_id) <> p_variant_id
                then p_variant_id else null end
    from kho_items i where i.id = r.item_id;

    v_items := array_append(v_items, r.item_id);
  end loop;

  if v_items is null then
    raise exception 'Bien the % chua co cong thuc kho', p_variant_id;
  end if;

  -- QUAN TRONG: p_origin='shopee' => Shopee DA tu tru cho dung listing khach mua,
  -- khong bat co day lai cho chinh no; cac listing anh em van phai day.
  perform kho_recalc_variant_stock(v_items, p_variant_id, p_origin);

  select stock into v_new from kho_variants where id = p_variant_id;
  return v_new;
end $function$;

