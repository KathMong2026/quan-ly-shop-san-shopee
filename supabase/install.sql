CREATE OR REPLACE FUNCTION public.kho_combo_mix_fix__impl(p_alert_id bigint, p_items jsonb)
 RETURNS text
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare a record; vid uuid; sl int; sn text; r record; e jsonb;
        tong_cu int := 0; tong_moi int := 0; v_items uuid[]; ghi text;
begin
  select * into a from kho_alerts where id = p_alert_id;
  if a.id is null then raise exception 'Khong tim thay thong bao %', p_alert_id; end if;
  if a.done_at is not null then raise exception 'Thong bao nay da xu ly roi'; end if;
  vid := (a.data->>'variant_id')::uuid;
  sl  := coalesce((a.data->>'qty')::int, 1);
  sn  := coalesce(a.data->>'order_sn','?');

  select coalesce(sum(b.qty*sl),0) into tong_cu from kho_variant_bom b where b.variant_id = vid;
  select coalesce(sum((x->>'qty')::int),0) into tong_moi from jsonb_array_elements(p_items) x;
  if tong_cu <> tong_moi then
    raise exception 'Số quần không khớp: công thức % cái, anh ghi % cái', tong_cu, tong_moi;
  end if;

  ghi := 'Sua mau combo mix - Don '||sn;
  -- hoan lai phan tru tam
  for r in select b.item_id, b.qty*sl q from kho_variant_bom b where b.variant_id = vid loop
    update kho_items set stock = stock + r.q where id = r.item_id;
    insert into kho_stock_movements(variant_id,item_id,change,reason,direction,note)
    values (vid, r.item_id, r.q, 'sua_combo_mix', 'none', ghi||' (hoan lai mau tru tam)');
    v_items := array_append(v_items, r.item_id);
  end loop;
  -- tru mau that
  for e in select * from jsonb_array_elements(p_items) loop
    update kho_items set stock = stock - (e->>'qty')::int where id = (e->>'item_id')::uuid;
    insert into kho_stock_movements(variant_id,item_id,change,reason,direction,note)
    values (vid, (e->>'item_id')::uuid, -(e->>'qty')::int, 'sua_combo_mix', 'none', ghi||' (mau that da dong)');
    v_items := array_append(v_items, (e->>'item_id')::uuid);
  end loop;

  perform kho_recalc_variant_stock(v_items, null, 'to_shopee');
  update kho_alerts set done_at = now(), read_at = coalesce(read_at, now()),
         done_note = 'Đã ghi màu thật cho đơn '||sn where id = p_alert_id;
  return 'Đã sửa '||tong_moi||' quần cho đơn '||sn;
end $function$;

