  n_mv int := 0; n_oi int := 0; n_pi int := 0; n_mir int := 0;
begin
  if p_old = p_new then raise exception 'Khong the gop 1 bien the vao chinh no'; end if;
  select * into v_old from public.kho_variants where id = p_old;
  select * into v_new from public.kho_variants where id = p_new;
  if v_old is null then raise exception 'Khong tim thay bien the cu'; end if;
  if v_new is null then raise exception 'Khong tim thay bien the moi'; end if;
  if v_old.product_id <> v_new.product_id then raise exception 'Chi gop duoc 2 bien the trong CUNG 1 san pham'; end if;
  if v_new.archived_at is not null then raise exception 'Bien the dich cung da bi xoa tren Shopee - chon ban khac'; end if;

  update public.kho_stock_movements set variant_id = p_new where variant_id = p_old;
  get diagnostics n_mv = row_count;
  update public.kho_stock_movements set via_variant_id = p_new where via_variant_id = p_old;

  update public.kho_order_items set variant_id = p_new where variant_id = p_old;
  get diagnostics n_oi = row_count;

  update public.kho_purchase_items set variant_id = p_new where variant_id = p_old;
  get diagnostics n_pi = row_count;

  -- cac bien the dang "soi guong" ban cu -> chuyen sang soi guong ban moi
  update public.kho_variants set mirrors_variant_id = p_new where mirrors_variant_id = p_old;
  get diagnostics n_mir = row_count;

  -- ban cu dang la mirror cua ai do ma ban moi chua lien ket -> ke thua lien ket
  if v_old.mirrors_variant_id is not null and v_new.mirrors_variant_id is null then
    update public.kho_variants set mirrors_variant_id = v_old.mirrors_variant_id where id = p_new;
  end if;

  -- ke thua gia von neu ban moi chua co
  if coalesce(v_new.cost_price,0) = 0 and coalesce(v_old.cost_price,0) > 0 then
    update public.kho_variants set cost_price = v_old.cost_price where id = p_new;
  end if;

  insert into public.kho_stock_movements(variant_id, change, reason, direction, note, synced, synced_at)
  values (p_new, 0, 'gop_bien_the', 'none',
          'Gop tu ban cu "' || coalesce(v_old.variant_name,'') || '" (SKU ' || coalesce(v_old.sku,'-') ||
          ', da bi xoa phan loai tren Shopee). Ton cu treo lai: ' || coalesce(v_old.stock,0) || ' - lay ton theo ban moi.',
          true, now());

  delete from public.kho_variants where id = p_old;

  return jsonb_build_object('movements', n_mv, 'order_items', n_oi, 'purchase_items', n_pi,
                            'mirrors_moved', n_mir, 'old_stock', coalesce(v_old.stock,0));
end;
$function$;

CREATE OR REPLACE FUNCTION public.kho_order_summary(raw jsonb)
 RETURNS text
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
declare it jsonb; n int := 0; first text := null; nm text;
begin
  for it in select * from jsonb_array_elements(coalesce(raw->'item_list','[]'::jsonb)) loop
    n := n + 1;
    if first is null then
      nm := coalesce(it->>'item_name','');
      if length(nm) > 40 then nm := rtrim(left(nm, 38), ' ,.-') || '…'; end if;
      first := nm
        || case when coalesce(it->>'model_name','') <> '' then ' (' || (it->>'model_name') || ')' else '' end
        || ' ×' || coalesce(it->>'model_quantity_purchased','1');
    end if;
  end loop;
  if first is null then return ''; end if;
  if n > 1 then first := first || ' · +' || (n-1) || ' SP khác'; end if;
  return first;
end $function$;

CREATE OR REPLACE FUNCTION public.kho_recalc_variant_stock(p_item_ids uuid[], p_skip_variant uuid DEFAULT NULL::uuid, p_origin text DEFAULT 'manual'::text)
