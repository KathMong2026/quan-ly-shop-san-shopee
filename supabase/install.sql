-- Chỉ chạy khi đã kết nối shop (có shop_id) và máy chủ đã tự ghi địa chỉ (function_url).
select cron.schedule('kho-shopee-pull-orders', '*/20 * * * *', $c$
  select net.http_post(
    url := s.function_url || '?action=pull_orders&days=1',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-cron-secret', a.cron_secret),
    timeout_milliseconds := 120000)
  from public.kho_settings s, public.kho_auth a
  where s.id = 1 and a.id = 1 and s.function_url is not null and s.shop_id is not null
$c$);
-- Sao lưu kho mỗi đêm 23:40 giờ VN (= 16:40 UTC), có so với tồn trên Shopee
select cron.schedule('kho-shopee-backup-daily', '40 16 * * *', $c$
  select net.http_post(
    url := s.function_url || '?action=backup_run&kind=auto&label=T%E1%BB%B1%20%C4%91%E1%BB%99ng%20h%E1%BA%B1ng%20ng%C3%A0y',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-cron-secret', a.cron_secret),
    timeout_milliseconds := 120000)
  from public.kho_settings s, public.kho_auth a
  where s.id = 1 and a.id = 1 and s.function_url is not null and s.shop_id is not null
$c$);
-- Dự phòng 23:55 VN: nếu tối nay chưa có bản sao lưu tự động thì chụp bằng SQL
select cron.schedule('kho-shopee-backup-fallback', '55 16 * * *', $c$
  select public.kho_create_backup__impl('auto', 'Tự động (dự phòng)', 'Chụp bằng SQL vì chưa có bản tự động nào trong ngày')
  where exists (select 1 from public.kho_settings where id = 1 and shop_id is not null)
    and not exists (select 1 from public.kho_backups where kind = 'auto'
      and (taken_at at time zone 'Asia/Bangkok')::date = (now() at time zone 'Asia/Bangkok')::date)
$c$);
