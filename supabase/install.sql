CREATE OR REPLACE FUNCTION public.kho_set_variant_bom__impl(p_variant_id uuid, p_items jsonb)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_items uuid[]; v_new int;
begin
  if not exists (select 1 from kho_variants where id = p_variant_id) then
    raise exception 'Khong tim thay bien the %', p_variant_id;
  end if;
  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Cong thuc phai co it nhat 1 ma hang';
  end if;

  select array_agg(item_id) into v_items from (
    select item_id from kho_variant_bom where variant_id = p_variant_id
    union
    select (e->>'item_id')::uuid from jsonb_array_elements(p_items) e
  ) x;

  delete from kho_variant_bom where variant_id = p_variant_id;
  insert into kho_variant_bom (variant_id, item_id, qty)
  select p_variant_id, (e->>'item_id')::uuid, greatest(1, coalesce((e->>'qty')::int, 1))
  from jsonb_array_elements(p_items) e
  on conflict (variant_id, item_id) do update set qty = excluded.qty;

  perform kho_recalc_variant_stock(v_items, null, 'manual');
  select stock into v_new from kho_variants where id = p_variant_id;
  return v_new;
end $function$;

CREATE OR REPLACE FUNCTION public.kho_snapshot_cost()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_cost numeric;
begin
  if (new.cost_price is null or new.cost_price = 0) and new.variant_id is not null then
    -- 1) tinh theo cong thuc kho (chinh xac cho combo)
    select sum(coalesce(i.cost_price, 0) * b.qty) into v_cost
    from kho_variant_bom b
    join kho_items i on i.id = b.item_id
    where b.variant_id = new.variant_id;

    -- 2) chua co cong thuc, hoac cac ma hang deu chua nhap gia von -> lay gia von cua listing
    if v_cost is null or v_cost = 0 then
      select coalesce(cost_price, 0) into v_cost from kho_variants where id = new.variant_id;
    end if;

    new.cost_price := coalesce(v_cost, 0);
  end if;
  new.cost_price := coalesce(new.cost_price, 0);
  return new;
end $function$;

CREATE OR REPLACE FUNCTION public.kho_variant_bom_autofill()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_item uuid;
begin
  if tg_op = 'INSERT' then
    perform kho_ensure_item_for_variant(new.id);
    return null;
  end if;

  if new.mirrors_variant_id is distinct from old.mirrors_variant_id then
    if new.mirrors_variant_id is not null then
      v_item := kho_ensure_item_for_variant(new.mirrors_variant_id);
      delete from kho_variant_bom where variant_id = new.id;
      insert into kho_variant_bom (variant_id, item_id, qty)
      values (new.id, v_item, 1) on conflict do nothing;
      perform kho_recalc_variant_stock(array[v_item], null, 'manual');
    else
      delete from kho_variant_bom where variant_id = new.id;
      v_item := kho_ensure_item_for_variant(new.id);
      perform kho_recalc_variant_stock(array[v_item], null, 'manual');
    end if;
  end if;
  return null;
end $function$;

