-- Chủ shop: ai đăng nhập ĐẦU TIÊN (khi project chỉ có đúng 1 tài khoản) thì thành chủ shop.
create or replace function public.kho_is_owner() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce(lower((select auth.jwt()) ->> 'email') = lower((select owner_email from public.kho_settings where id = 1)), false)
$$;

create or replace function public.kho_setup_state() returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object('installed', true,
    'has_owner', exists (select 1 from public.kho_settings where id = 1 and owner_email is not null))
$$;

create or replace function public.kho_claim_owner() returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_email text := lower(nullif((select auth.jwt()) ->> 'email', ''));
  v_owner text;
begin
  if v_email is null then raise exception 'Chua dang nhap' using errcode = '42501'; end if;
  select lower(owner_email) into v_owner from public.kho_settings where id = 1 for update;
  if v_owner is null and (select count(*) from auth.users) = 1 then
    update public.kho_settings set owner_email = v_email, updated_at = now() where id = 1;
    v_owner := v_email;
  end if;
  return jsonb_build_object('is_owner', v_owner is not null and v_owner = v_email, 'has_owner', v_owner is not null);
end $$;

revoke all on function public.kho_is_owner() from public, anon;
grant execute on function public.kho_is_owner() to authenticated;
revoke all on function public.kho_setup_state() from public;
grant execute on function public.kho_setup_state() to anon, authenticated;
revoke all on function public.kho_claim_owner() from public, anon;
grant execute on function public.kho_claim_owner() to authenticated;

