CREATE OR REPLACE FUNCTION public.kho_restore_backup_items__impl(p_backup_id bigint)
 RETURNS TABLE(so_ma_hang_sua integer, tong_thay_doi integer)
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r record; n int := 0; s int := 0; d int;
begin
  if not exists (select 1 from kho_backups where id = p_backup_id) then
    raise exception 'Khong tim thay ban sao luu %', p_backup_id;
  end if;

  for r in
    select l.ref_id, l.sku, l.stock_app, i.stock as hien_tai
    from kho_backup_lines l
    join kho_items i on i.id = l.ref_id
    where l.backup_id = p_backup_id and l.loai = 'item'
      and i.stock is distinct from l.stock_app
    order by l.sku
  loop
    d := r.stock_app - coalesce(r.hien_tai, 0);
    perform kho_adjust_item_stock(
      r.ref_id, d,
      case when d > 0 then 'kiem_ke_tang' else 'kiem_ke_giam' end,
      'none',
      format('Khoi phuc tu ban sao luu #%s (%s -> %s)', p_backup_id, r.hien_tai, r.stock_app));
    n := n + 1; s := s + d;
  end loop;

  return query select n, s;
end $function$;

