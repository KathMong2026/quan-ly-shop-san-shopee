CREATE OR REPLACE FUNCTION public.kho_receive_purchase__impl(p_purchase_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r record; v_stock int; v_cost numeric; v_new numeric; v_total numeric := 0; v_line_total numeric; v_eff_cost numeric;
begin
  if not exists (select 1 from public.kho_purchases where id = p_purchase_id) then raise exception 'Không tìm thấy phiếu nhập'; end if;
  if exists (select 1 from public.kho_purchases where id = p_purchase_id and status = 'received') then raise exception 'Phiếu này đã nhận hàng rồi'; end if;
  for r in select * from public.kho_purchase_items where purchase_id = p_purchase_id loop
    v_line_total := coalesce(r.qty,0) * coalesce(r.unit_cost,0) - coalesce(r.discount,0);
    v_total := v_total + v_line_total;
    if r.variant_id is not null and coalesce(r.qty,0) > 0 then
      v_eff_cost := v_line_total / r.qty;
      select stock, coalesce(cost_price,0) into v_stock, v_cost from public.kho_variants where id = r.variant_id for update;
      if v_stock is null then continue; end if;
      if (v_stock + r.qty) > 0 then v_new := (v_stock * v_cost + r.qty * v_eff_cost) / (v_stock + r.qty);
      else v_new := v_eff_cost; end if;
      update public.kho_variants set cost_price = round(v_new) where id = r.variant_id;
      perform public.kho_adjust_stock(r.variant_id, r.qty, 'purchase', 'to_shopee', 'Nhập hàng theo phiếu');
    end if;
  end loop;
  update public.kho_purchases set status = 'received', received_at = now(), total_cost = v_total where id = p_purchase_id;
end $function$;

