 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$ begin perform public.kho_assert_owner(); return public.kho_adjust_item_stock__impl($1, $2, $3, $4, $5); end $function$;

CREATE OR REPLACE FUNCTION public.kho_adjust_item_stock__impl(p_item_id uuid, p_change integer, p_reason text, p_direction text DEFAULT 'none'::text, p_note text DEFAULT NULL::text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_new int; v_variant uuid;
begin
  update kho_items set stock = stock + p_change where id = p_item_id
  returning stock, source_variant_id into v_new, v_variant;
  if v_new is null then raise exception 'Khong tim thay ma hang %', p_item_id; end if;

  if v_variant is null then
    select variant_id into v_variant from kho_variant_bom
    where item_id = p_item_id order by variant_id limit 1;
  end if;

  insert into kho_stock_movements (variant_id, item_id, change, reason, direction, note)
  values (v_variant, p_item_id, p_change, p_reason, p_direction, p_note);

  perform kho_recalc_variant_stock(array[p_item_id], null, 'manual');
  return v_new;
end $function$;

