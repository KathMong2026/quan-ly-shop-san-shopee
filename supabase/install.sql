CREATE OR REPLACE FUNCTION public.kho_ensure_item_for_variant__impl(p_variant_id uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v kho_variants%rowtype; v_item uuid;
begin
  select * into v from kho_variants where id = p_variant_id;
  if not found then raise exception 'Khong tim thay bien the %', p_variant_id; end if;

  select item_id into v_item from kho_variant_bom where variant_id = p_variant_id limit 1;
  if v_item is not null then return v_item; end if;

  -- mirror cu: bam vao ma hang cua bien the goc
  if v.mirrors_variant_id is not null then
    select id into v_item from kho_items where source_variant_id = v.mirrors_variant_id;
    if v_item is null then
      v_item := kho_ensure_item_for_variant(v.mirrors_variant_id);
    end if;
    insert into kho_variant_bom (variant_id, item_id, qty)
    values (p_variant_id, v_item, 1) on conflict do nothing;
    return v_item;
  end if;

  select id into v_item from kho_items where source_variant_id = p_variant_id;
  if v_item is null then
    insert into kho_items (sku, name, stock, cost_price, source_variant_id)
    select kho_item_sku_unique(v.sku, v.id),
           p.name || ' — ' || coalesce(nullif(trim(v.variant_name), ''), '(mặc định)'),
           coalesce(v.stock, 0), coalesce(v.cost_price, 0), v.id
    from kho_products p where p.id = v.product_id
    returning id into v_item;
  end if;

  insert into kho_variant_bom (variant_id, item_id, qty)
  values (p_variant_id, v_item, 1) on conflict do nothing;
  return v_item;
end $function$;

