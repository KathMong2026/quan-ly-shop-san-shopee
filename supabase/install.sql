CREATE OR REPLACE FUNCTION public.kho_recalc_variant_stock__impl(p_item_ids uuid[], p_skip_variant uuid DEFAULT NULL::uuid, p_origin text DEFAULT 'manual'::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  update kho_variants v
     set stock = t.new_stock,
         needs_sync_shopee = case when p_origin = 'shopee' and v.id = p_skip_variant
                                  then v.needs_sync_shopee else true end,
         needs_sync_lazada = case when p_origin = 'lazada' and v.id = p_skip_variant
                                  then v.needs_sync_lazada else true end
    from (
      select b.variant_id, min(floor(i.stock::numeric / b.qty))::int as new_stock
      from kho_variant_bom b
      join kho_items i on i.id = b.item_id
      where b.variant_id in (
        select b2.variant_id from kho_variant_bom b2 where b2.item_id = any(p_item_ids)
      )
      group by b.variant_id
    ) t
   where v.id = t.variant_id;
end $function$;

